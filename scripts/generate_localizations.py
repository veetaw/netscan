"""Generate the compile-time catalog from the reviewed English/Italian sources."""
import json
from pathlib import Path

def literal(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')

result = '// Generated by scripts/generate_localizations.py. Edit assets/l10n/*.json.\n'
for code, variable in [('en', 'english'), ('it', 'italian')]:
    data = json.loads(Path(f'assets/l10n/{code}.json').read_text())
    result += f'const {variable} = <String, String>{{\n'
    result += ''.join(f'  {literal(k)}: {literal(v)},\n' for k, v in data.items())
    result += '};\n'
Path('lib/l10n/catalog.dart').write_text(result)
